#!/usr/bin/env python3
"""Generate app/imgtest.tsx: an expo-image test route with a large data: URI
(824x1830 PNG, base64 ~215KB) to reproduce the Android blank-image case on the
PR APK without touching a real chat. Tune noise blocks so the PNG lands near
161,280 raw bytes (~215KB base64, matching the production repro)."""

import base64
import io
import random

from PIL import Image, ImageDraw, ImageFont

W, H = 824, 1830
TARGET_RAW = 161_280
OUT_TSX = "app/imgtest.tsx"

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def draw_base():
    img = Image.new("RGB", (W, H))
    px = img.load()
    for y in range(H):  # vertical gradient, dark navy -> dark maroon
        t = y / H
        for x in range(W):  # slight horizontal tint to defeat trivial compression
            r = int(16 + 26 * t + 6 * (x / W))
            g = int(24 - 10 * t)
            b = int(32 + 24 * (1 - t) + 4 * (x / W))
            px[x, y] = (r, g, b)
    d = ImageDraw.Draw(img, "RGBA")
    for gx in range(0, W + 1, 122):  # grid
        d.line([(gx, 0), (gx, H)], fill=(255, 255, 255, 40), width=1)
    for gy in range(0, H + 1, 122):
        d.line([(0, gy), (W, gy)], fill=(255, 255, 255, 40), width=1)
    for y in range(0, H, 200):  # ruler ticks + labels
        d.line([(0, y), (26, y)], fill=(255, 255, 0, 200), width=3)
        d.text((34, y - 9), f"y={y}", font=ImageFont.truetype(FONT, 20),
               fill=(255, 255, 160, 230))
    for (cx, cy) in [(60, 60), (W - 60, 60), (60, H - 60), (W - 60, H - 60), (W // 2, H // 2)]:
        d.line([(cx - 40, cy), (cx + 40, cy)], fill=(255, 0, 0, 220), width=4)
        d.line([(cx, cy - 40), (cx, cy + 40)], fill=(255, 0, 0, 220), width=4)
    big = ImageFont.truetype(FONT, 64)
    d.text((W // 2, 160), "TOP", font=big, fill=(255, 90, 90), anchor="mm")
    d.text((W // 2, H - 160), "BOTTOM", font=big, fill=(90, 160, 255), anchor="mm")
    d.text((W // 2, H // 2 - 70), "824 x 1830", font=big, fill=(255, 255, 255), anchor="mm")
    d.text((W // 2, H // 2 + 20), "expo-image data: URI test", font=ImageFont.truetype(FONT, 34),
           fill=(200, 255, 200), anchor="mm")
    d.text((W // 2, 34), "IF BLANK -> decode failed   IF FULL -> decode ok", font=ImageFont.truetype(FONT, 22),
           fill=(255, 255, 255), anchor="mm")
    sw = ["#e63946", "#f4a261", "#e9c46a", "#8ac926", "#2a9d8f", "#219ebc", "#8338ec", "#ff006e"]
    sw_w = W // len(sw)
    for i, c in enumerate(sw):  # color strip mid-frame
        d.rectangle([i * sw_w, int(H * 0.55), (i + 1) * sw_w, int(H * 0.55) + 80], fill=c)
    return img


def with_noise(base, block):
    img = base.copy()
    d = ImageDraw.Draw(img)
    rng = random.Random(42)
    for y in range(0, H, block):
        for x in range(0, W, block):
            c = (rng.randrange(256), rng.randrange(256), rng.randrange(256))
            d.rectangle([x, y, x + block - 1, y + block - 1], fill=c)
    return img


def encode(img):
    buf = io.BytesIO()
    img.save(buf, "PNG", compress_level=6)
    return buf.getvalue()


def gen_tsx(b64):
    return (
        "import { View, Text, ScrollView } from \"react-native\"\n"
        "import { Image } from \"expo-image\"\n"
        "import { useState } from \"react\"\n"
        "import { imageError, imageLoad } from \"../src/lib/image-diagnostics.ts\"\n\n"
        "// Generated by scripts/gen-imgtest-asset.py — 824x1830 PNG, base64 ~200KB.\n"
        "const LARGE = `data:image/png;base64," + b64 + "`\n\n"
        "const CONTROL =\n"
        "  \"data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==\"\n\n"
        "const CELLS = [\n"
        "  { k: \"big-contain\", fit: \"contain\", w: 150, h: 150 },\n"
        "  { k: \"big-cover\", fit: \"cover\", w: 150, h: 150 },\n"
        "  { k: \"big-none\", fit: \"none\", w: 150, h: 150 },\n"
        "  { k: \"big-fill\", fit: \"fill\", w: 150, h: 150 },\n"
        "  { k: \"huge-cover\", fit: \"cover\", w: 150, h: 305 },\n"
        "  { k: \"huge-contain\", fit: \"contain\", w: 150, h: 305 },\n"
        "  { k: \"ctl-small\", fit: \"cover\", w: 150, h: 150, small: true },\n"
        "] as const\n\n"
        "export default function ImgTest() {\n"
        "  const [fit, setFit] = useState<Record<string, string>>({})\n"
        "  const mark = (k: string, v: string) => setFit((f) => ({ ...f, [k]: v }))\n"
        "  const uri = (c: (typeof CELLS)[number]) => (\"small\" in c ? CONTROL : LARGE)\n"
        "  return (\n"
        "    <ScrollView contentContainerStyle={{ padding: 12, gap: 10, backgroundColor: \"#101820\" }}>\n"
        "      <Text style={{ color: \"#fff\", fontSize: 13 }}>\n"
        "        {CELLS.map((c) => c.k + \": \" + (fit[c.k] ?? \"pending\")).join(\"\\n\")}\n"
        "      </Text>\n"
        "      <View style={{ flexDirection: \"row\", flexWrap: \"wrap\", gap: 8 }}>\n"
        "        {CELLS.map((c) => (\n"
        "          <Image\n"
        "            key={c.k}\n"
        "            source={{ uri: uri(c) }}\n"
        "            style={{ width: c.w, height: c.h, backgroundColor: \"#e5e5e5\" }}\n"
        "            contentFit={c.fit}\n"
        "            recyclingKey={\"img-\" + c.k}\n"
        "            onLoad={(e) => {\n"
        "              mark(c.k, \"load \" + e.source.width + \"x\" + e.source.height)\n"
        "              imageLoad(\"imgtest-\" + c.k, uri(c), e.source.width, e.source.height)\n"
        "            }}\n"
        "            onError={(e) => {\n"
        "              mark(c.k, e.error ?? \"error\")\n"
        "              imageError(\"imgtest-\" + c.k, uri(c), e.error)\n"
        "            }}\n"
        "          />\n"
        "        ))}\n"
        "      </View>\n"
        "      <Text style={{ color: \"#9ab\" }}>{\"route: /imgtest | boxes use one large data: URI | breadcrumbs: [image]\"}</Text>\n"
        "    </ScrollView>\n"
        "  )\n"
        "}\n"
    )


def main():
    base = draw_base()
    best = (0, 0, None)  # (block, raw, encoded) closest to target
    for block in (64, 48, 32, 24, 16, 12, 8, 7, 6, 4):  # tune entropy toward target size
        img = with_noise(base, block)
        raw = encode(img)
        print(f"block={block:>2} raw={len(raw):>8} b64={len(base64.b64encode(raw)):>8}")
        if abs(len(raw) - TARGET_RAW) < abs(best[1] - TARGET_RAW) or best[2] is None:
            best = (block, len(raw), raw)
    _, _, raw = best
    b64 = base64.b64encode(raw).decode()
    print(f"final raw={len(raw)} b64={len(b64)}")
    tsx = gen_tsx(b64)
    open(OUT_TSX, "w").write(tsx)
    print(f"wrote {OUT_TSX} ({len(tsx)} bytes)")


if __name__ == "__main__":
    main()
